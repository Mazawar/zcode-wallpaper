export async function ensureShortcutsHaveCdpFlag(port: number): Promise<ShortcutSyncResult> {
  if (process.platform === "darwin") return ensureMacLauncher(port);
  if (process.platform !== "win32") return ensureLinuxDesktopEntries(port);
  return ensureWindowsShortcuts(port);
}

// --- windows -------------------------------------------------------------------

/** Directories that hold ZCode launch shortcuts, in priority order. */
function shortcutDirs(): string[] {
  const home = process.env.USERPROFILE ?? "";
  const appData = process.env.APPDATA ?? "";
  return [
    // Desktop may be OneDrive-redirected; cover both physical locations.
    path.join(home, "Desktop"),
    ...(process.env.OneDrive ? [path.join(process.env.OneDrive, "Desktop")] : []),
    path.join(appData, "Microsoft", "Windows", "Start Menu", "Programs"),
    path.join("C:", "ProgramData", "Microsoft", "Windows", "Start Menu", "Programs"),
    path.join(appData, "Microsoft", "Internet Explorer", "Quick Launch", "User Pinned", "TaskBar"),
  ];
}

async function ensureWindowsShortcuts(port: number): Promise<ShortcutSyncResult> {
  const result: ShortcutSyncResult = { updated: [], skipped: [], failed: [] };

  const links: string[] = [];
  const collect = (dir: string) => {
    links.push(...fs.readdirSync(dir).filter((f) => /^zcode/i.test(f) && f.endsWith(".lnk")).map((f) => path.join(dir, f)));
  };
  for (const dir of shortcutDirs()) {
    try {
      collect(dir);
      // One subdirectory level (desktop folders like "agent", start-menu groups).
      for (const sub of fs.readdirSync(dir, { withFileTypes: true })) {
        if (!sub.isDirectory()) continue;
        try {
          collect(path.join(dir, sub.name));
        } catch {
          /* unreadable subdir */
        }
      }
    } catch {
      /* dir absent */
    }
  }
  if (links.length === 0) return result;

  // Early-launch wrapper (D18, hardened): the .lnk points at a generated
  // .vbs that starts the wallpaper serve hidden BEFORE ZCode — the renderer
  // page exists at ~1s while plugin hosts spawn ~10s later. The wrapper can
  // NEVER block a launch: the serve only runs when node AND the plugin both
  // exist, errors are swallowed, and the ZCode line runs unconditionally.
  // Node/cli paths are baked per machine and re-baked by every plugin
  // session (writeEarlyLaunchVbs below), so an nvm move degrades to "no
  // early serve" until the next session — never to "ZCode won't start".
  const launcher = launcherHome();
  const vbsFile = path.join(launcher.dir, "zw-launch.vbs");
  const metaFile = path.join(launcher.dir, "zw-launch.json");
  let zcodeKnown = "";

  const antiOcclusion = ANTI_OCCLUSION_FLAGS;
  for (const lnk of links) {
    const script = `
$ErrorActionPreference = 'Stop'
try {
  $ws = New-Object -ComObject WScript.Shell
  $s = $ws.CreateShortcut('${lnk.replace(/'/g, "''")}')
  $vbs = '${vbsFile.replace(/'/g, "''")}'
  $meta = Get-Content -Raw '${metaFile.replace(/'/g, "''")}' -ErrorAction SilentlyContinue | ConvertFrom-Json
  $zcode = $null
  if ($s.TargetPath -match 'ZCode\\.exe$') { $zcode = $s.TargetPath }
  elseif ($s.TargetPath -match 'wscript\\.exe$' -and ([string]$s.Arguments) -match 'zw-launch\\.vbs') {
    # Already wrapped by this or an earlier install generation: recover the
    # ZCode exe from the wrapper's sibling meta json (ours first, then any
    # generation the .lnk itself names).
    if ($meta) { $zcode = $meta.zcode }
    if (-not $zcode) {
      $vbsArg = ([regex]::Match([string]$s.Arguments, '"([^"]+zw-launch\\.vbs)"')).Groups[1].Value
      if (-not $vbsArg) { $vbsArg = (([string]$s.Arguments -split ' ')[0] -replace '^"|"$','') }
      if ($vbsArg -and (Test-Path $vbsArg)) {
        $metaPath = Join-Path (Split-Path $vbsArg -Parent) 'zw-launch.json'
        if (Test-Path $metaPath) { try { $zcode = (Get-Content -Raw $metaPath | ConvertFrom-Json).zcode } catch {} }
      }
    }
  }
  # Last resort: a shortcut copied from ANOTHER machine (synced Desktop,
  # copied .zcode dir) points at a wrapper path that does not exist here and
  # its meta names a foreign ZCode.exe — the original target is unrecoverable
  # from the .lnk. Probe this machine's install locations instead so the sync
  # can rewrite the entry into a locally valid one instead of skipping forever.
  if (-not $zcode -or -not (Test-Path $zcode)) {
    $cands = @()
    if ($env:ZCODE_WINDOWS_APP_INSTALL_DIR) { $cands += (Join-Path $env:ZCODE_WINDOWS_APP_INSTALL_DIR 'ZCode.exe') }
    $cands += 'C:\\Program Files\\ZCode\\ZCode.exe'
    $cands += (Join-Path $env:LOCALAPPDATA 'Programs\\ZCode\\ZCode.exe')
    foreach ($c in $cands) { if (Test-Path $c) { $zcode = $c; break } }
  }
  if (-not $zcode) { Write-Output 'ok|not-zcode'; exit }
  if (-not (Test-Path $zcode)) { Write-Output ('ok|zcode-missing|' + $zcode); exit }
  $anti = @('${antiOcclusion.join("', '")}')
  # rebuild zcode args: strip any wrapper reference + managed flags, append canonical
  $argStr = ([string]$s.Arguments) -replace '^"[^"]*zw-launch\.vbs"\s*','' -replace '^\S*zw-launch\.vbs\s*',''
  $parts = @($argStr -split ' ' | Where-Object { $_ -ne '' -and $_ -notlike '--remote-debugging-port=*' -and $anti -notcontains $_ })
  $canonical = @('--remote-debugging-port=${port}') + $anti
  $zargs = ($parts + $canonical) -join ' '
  $newArgs = '"' + $vbs + '" ' + $zargs
  # Fast path: already wrapped exactly as we would wrap it (the .vbs content
  # itself is refreshed from TypeScript below, no marker juggling needed).
  if ($s.TargetPath -eq 'wscript.exe' -and ([string]$s.Arguments) -eq $newArgs -and (Test-Path $vbs)) {
    Write-Output ('ok|has-flag|' + $zcode); exit
  }
  if (-not $s.IconLocation -or $s.IconLocation -eq ',0' -or $s.IconLocation -like '*zw-launch*') { $s.IconLocation = $zcode + ',0' }
  $s.WorkingDirectory = Split-Path $zcode -Parent
  $s.TargetPath = 'wscript.exe'
  $s.Arguments = $newArgs
  $s.Save()
  Write-Output ('updated|' + $zcode)
} catch { Write-Output ('err|' + $_.Exception.Message) }`;
    try {
      const { stdout } = await exec("powershell", ["-NoProfile", "-Command", script], { timeout: 15_000, windowsHide: true });
      const out = stdout.trim();
      const zcode = out.includes("|") ? out.slice(out.indexOf("|") + 1) : "";
      if (zcode && !zcodeKnown) zcodeKnown = zcode;
      if (out.startsWith("updated")) {
        result.updated.push(lnk);
      } else if (out.startsWith("err")) {
        result.failed.push({ path: lnk, reason: out.slice(4) });
      } else {
        result.skipped.push(lnk);
      }
    } catch (err) {
      result.failed.push({ path: lnk, reason: (err as Error).message });
    }
  }

  // Refresh the wrapper on EVERY pass (not only when a shortcut changed):
  // its baked node/cli paths must track nvm moves and plugin updates. The
  // vbs text embeds all four inputs (node, cli, zcode, port), so a content
  // compare against the file on disk is the complete staleness check.
  if (zcodeKnown) writeEarlyLaunchVbs(port, zcodeKnown, launcher);
  return result;
}

/** Writes the early-launch zw-launch.vbs (+ meta json with the ZCode exe for
 *  shortcut recovery). Hardened per D18: the serve step is guarded by BOTH
 *  node and plugin existence, every error is swallowed, and the ZCode launch
 *  line is unconditional — this file must never be able to stop ZCode from
 *  starting. Idempotent by content comparison. */
function writeEarlyLaunchVbs(port: number, zcode: string, launcher: { dir: string; root: string }): void {
  const anti = ANTI_OCCLUSION_FLAGS;
  const cli = path.join(launcher.root, "dist", "cli.js");
  const node = process.execPath;
  if (!fs.existsSync(cli) || !fs.existsSync(node)) return;
  // v6 observability: the serve now runs through a generated zw-serve.cmd
  // whose plain cmd quoting appends stdout+stderr to the shared serve log —
  // the same file every serve form's ring buffer tees into (server.ts). The
  // old sh.Run spawn discarded all output, so a serve failing at boot left
  // zero evidence (2026-10-28: two boots, no attribution possible).
  const DQ = String.fromCharCode(34);
  const logFile = path.join(launcher.dir, "zw-serve.log");
  const cmdFile = path.join(launcher.dir, "zw-serve.cmd");
  const serveBat = [
    "@echo off",
    `"${node}" "${cli}" serve --early --port ${port} --api-port ${port + 1} >> "${logFile}" 2>&1`,
    "",
  ].join("\r\n");
  // FileExists takes a plain quoted literal — NOT the doubled sh.Run
  // command-line escaping (cscript compile-checks this).
  const flags = [`--remote-debugging-port=${port}`, ...anti].join(" ");
  const lines = [
    String.fromCharCode(39) + " zcode-wallpaper early launch zw-wrapper-v6 (generated by the plugin)",
    String.fromCharCode(39) + " Starts the wallpaper serve hidden BEFORE ZCode so the renderer page",
    String.fromCharCode(39) + " is injected the moment it exists (plugin hosts spawn ~10s later).",
    String.fromCharCode(39) + " D18 HARD RULE: this wrapper must never block ZCode from starting —",
    String.fromCharCode(39) + " the serve only runs when node AND the plugin both exist, and the",
    String.fromCharCode(39) + " ZCode launch below runs unconditionally. If the baked ZCode path",
    String.fromCharCode(39) + " went stale (app moved/reinstalled elsewhere), the standard install",
    String.fromCharCode(39) + " locations are probed before giving up with an explicit message.",
    String.fromCharCode(39) + " v6: every step leaves a line in zw-serve.log (rotated at 256 KB);",
    String.fromCharCode(39) + " the serve itself runs via zw-serve.cmd so its output is captured.",
    "On Error Resume Next",
    "Set sh = CreateObject(\"WScript.Shell\")",
    "Set fso = CreateObject(\"Scripting.FileSystemObject\")",
    "logf = " + DQ + logFile + DQ,
    "If fso.FileExists(logf) Then",
    "  If fso.GetFile(logf).Size > 262144 Then",
    "    fso.DeleteFile logf & \".old\", True",
    "    fso.MoveFile logf, logf & \".old\"",
    "  End If",
    "End If",
    "Sub ZLog(m)",
    "  On Error Resume Next",
    "  Set lf = fso.OpenTextFile(logf, 8, True)",
    "  lf.WriteLine Year(Now) & \"-\" & Right(\"0\" & Month(Now), 2) & \"-\" & Right(\"0\" & Day(Now), 2) & \" \" & Right(\"0\" & Hour(Now), 2) & \":\" & Right(\"0\" & Minute(Now), 2) & \":\" & Right(\"0\" & Second(Now), 2) & \" vbs: \" & m",
    "  lf.Close",
    "End Sub",
    "ZLog \"wrapper v6 boot\"",
    "If fso.FileExists(" + DQ + node + DQ + ") And fso.FileExists(" + DQ + cli + DQ + ") Then",
    "  ZLog \"spawning serve via zw-serve.cmd\"",
    "  sh.Run " + DQ + cmdFile + DQ + ", 0, False",
    "Else",
    "  ZLog \"serve skipped: node or cli missing\"",
    "End If",
    "orig = " + DQ + zcode + DQ,
    "zc = orig",
    "If Not fso.FileExists(zc) Then",
    "  zc = " + DQ + DQ,
    "  p = sh.ExpandEnvironmentStrings(\"%ZCODE_WINDOWS_APP_INSTALL_DIR%\") & \"\\ZCode.exe\"",
    "  If fso.FileExists(p) Then zc = p",
    "  p = \"C:\\Program Files\\ZCode\\ZCode.exe\"",
    "  If zc = \"\" And fso.FileExists(p) Then zc = p",
    "  p = sh.ExpandEnvironmentStrings(\"%LOCALAPPDATA%\") & \"\\Programs\\ZCode\\ZCode.exe\"",
    "  If zc = \"\" And fso.FileExists(p) Then zc = p",
    // any install location: a running ZCode instance knows its own path
    "  If zc = \"\" Then",
    "    Set wmi = GetObject(\"winmgmts:\\\\.\\root\\cimv2\")",
    "    For Each pr In wmi.ExecQuery(\"Select ExecutablePath From Win32_Process Where Name = 'ZCode.exe'\")",
    "      If zc = \"\" And Len(pr.ExecutablePath) > 0 Then zc = pr.ExecutablePath",
    "    Next",
    "  End If",
    // any install location: a shortcut that still points at ZCode.exe (a
    // moved install's setup drops fresh ones before the plugin ever runs)
    "  If zc = \"\" Then",
    "    sfa = Array(sh.SpecialFolders(\"Desktop\"), sh.SpecialFolders(\"AllUsersDesktop\"), sh.SpecialFolders(\"Programs\"), sh.SpecialFolders(\"AllUsersPrograms\"))",
    "    For Each sd In sfa",
    "      If zc = \"\" And Len(sd) > 0 Then",
    "        For Each f In fso.GetFolder(sd).Files",
    "          If LCase(fso.GetExtensionName(f.Name)) = \"lnk\" Then",
    "            tp = sh.CreateShortcut(f.Path).TargetPath",
    "            If LCase(Right(tp, 9)) = \"zcode.exe\" And fso.FileExists(tp) Then zc = tp",
    "          End If",
    "        Next",
    "        For Each sf2 In fso.GetFolder(sd).SubFolders",
    "          For Each f In sf2.Files",
    "            If zc = \"\" And LCase(fso.GetExtensionName(f.Name)) = \"lnk\" Then",
    "              tp = sh.CreateShortcut(f.Path).TargetPath",
    "              If LCase(Right(tp, 9)) = \"zcode.exe\" And fso.FileExists(tp) Then zc = tp",
    "            End If",
    "          Next",
    "        Next",
    "      End If",
    "    Next",
    "  End If",
    // last ditch: root-level custom installs like D:\ZCode
    "  For d = 67 To 90",
    "    p = Chr(d) & \":\\ZCode\\ZCode.exe\"",
    "    If zc = \"\" And fso.FileExists(p) Then zc = p",
    "  Next",
    "End If",
    "fl = " + DQ + flags + DQ,
    "If zc <> \"\" Then",
    "  ZLog \"launching zcode: \" & zc",
    "  sh.Run Chr(34) & zc & Chr(34) & \" \" & fl, 1, False",
    "Else",
    "  ZLog \"zcode not found - showing fallback dialog\"",
    "  MsgBox " + DQ + msgBoxText(zcode) + DQ + ", 48, \"zcode-wallpaper\"",
    "End If",
  ];  const crlf = String.fromCharCode(13, 10);
  const want = lines.join(crlf) + crlf;
  const vbsFile = path.join(launcher.dir, "zw-launch.vbs");
  try {
    const metaPath = path.join(launcher.dir, "zw-launch.json");
    const prev = fs.existsSync(metaPath) ? (JSON.parse(fs.readFileSync(metaPath, "utf8")) as Record<string, unknown>) : {};
    const sameVbs = fs.existsSync(vbsFile) && fs.readFileSync(vbsFile, "utf8") === want;
    const meta = { ...prev, zcode, node, cli, port };
    if (!sameVbs) {
      fs.writeFileSync(vbsFile, want, { encoding: "utf8" });
      fs.writeFileSync(cmdFile, serveBat, { encoding: "utf8" });
      console.log(`serve: early-launch wrapper refreshed (node=${node})`);
    } else if (!fs.existsSync(cmdFile)) {
      fs.writeFileSync(cmdFile, serveBat, { encoding: "utf8" });
    }
    if (JSON.stringify(prev) !== JSON.stringify(meta)) fs.writeFileSync(metaPath, JSON.stringify(meta, null, 1));
  } catch {
    /* unwritable location - shortcuts fall back to plain flag mode */
  }
}

/** ASCII-only fallback dialog text — wscript reads non-BOM files as the ANSI
 *  codepage, so no non-ASCII may appear anywhere in the wrapper. */
function msgBoxText(staleZcode: string): string {
  return (
    `ZCode.exe not found (was: ${staleZcode}). ` +
    "Start ZCode once from its install folder - the plugin will repair this shortcut automatically."
  );
}

// --- macOS -----------------------------------------------------------------------

const MAC_ZCODE_CANDIDATES = ["/Applications/ZCode.app", path.join(os.homedir(), "Applications", "ZCode.app")];

/**
 * Generates "ZCode Wallpaper.app" in ~/Applications — the macOS equivalent of
 * the Windows shortcut wrapper. macOS has no supported way to inject launch
 * args into Dock/Spotlight launches, so while the wallpaper plugin is enabled
 * the user launches ZCode through this app. Idempotent; rewritten whenever
 * the node/cli paths change.
 */
async function ensureMacLauncher(port: number): Promise<ShortcutSyncResult> {
  const result: ShortcutSyncResult = { updated: [], skipped: [], failed: [] };
  const zcodeApp = MAC_ZCODE_CANDIDATES.find((p) => fs.existsSync(p));
  if (!zcodeApp) {
    result.skipped.push("ZCode.app not found");
    return result;
  }
  const { dir, root } = launcherHome();
  const cli = path.join(root, "dist", "cli.js");
  if (!fs.existsSync(cli)) {
    result.skipped.push("plugin install not found");
    return result;
  }
  const appName = "ZCode Wallpaper.app";
  const appDir = path.join(os.homedir(), "Applications", appName);
  const scriptPath = path.join(appDir, "Contents", "MacOS", "zw-launch");
  const plistPath = path.join(appDir, "Contents", "Info.plist");
  const want = buildEarlyLaunchCommand(process.execPath, cli, port, zcodeApp, path.join(dir, "early.log"));
  try {
    const same =
      fs.existsSync(scriptPath) && fs.existsSync(plistPath) && fs.readFileSync(scriptPath, "utf8") === want;
    if (same) {
      result.skipped.push(appDir);
    } else {
      fs.mkdirSync(path.dirname(scriptPath), { recursive: true });
      fs.writeFileSync(scriptPath, want);
      fs.chmodSync(scriptPath, 0o755);
      fs.writeFileSync(plistPath, buildAppBundlePlist("ZCode Wallpaper", "com.zcode-wallpaper.early"));
      result.updated.push(appDir);
    }
  } catch (err) {
    result.failed.push({ path: appDir, reason: (err as Error).message });
  }
  return result;
}

