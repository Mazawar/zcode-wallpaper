/**
 * Early-launch support, per platform — starts the wallpaper serve BEFORE
 * ZCode so the renderer is injected the moment it exists (plugin hosts spawn
 * ~10s later):
 *   win32   rewrite ZCode .lnk shortcuts to a generated wscript wrapper
 *   darwin  generate a launcher .app bundle in ~/Applications the user
 *           launches instead of ZCode (serve first, then
 *           `open -a ZCode --args --remote-debugging-port=…`)
 *   linux   rewrite user-scope .desktop entries to a wrapper script
 *
 * ZCode only accepts --remote-debugging-port at process start, so an entry
 * without it means no injection for that whole session. Everything generated
 * is machine-local: node = the process running this plugin right now, the
 * cli path is probed from this install, ZCode's path comes from the entry
 * being rewritten. All launchers skip the serve when the plugin install is
 * gone (uninstall must never break launching ZCode). Content builders are
 * pure and unit-tested; only the scanning parts touch the OS.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileP as exec } from "./exec.js";
import { dataDir } from "./launch.js";

export interface ShortcutSyncResult {
  /** Shortcuts that gained the flag this run. */
  updated: string[];
  /** Shortcuts already carrying the flag (or not pointing at ZCode.exe). */
  skipped: string[];
  /** Shortcuts that could not be saved (typically ProgramData without elevation). */
  failed: Array<{ path: string; reason: string }>;
}

/** Chromium flags that stop occlusion misdetection from freezing media/rAF. */
export const ANTI_OCCLUSION_FLAGS = [
  "--disable-backgrounding-occluded-windows",
  "--disable-renderer-backgrounding",
];

/**
 * Where the generated launcher artifacts live. The data dir (~/.zcode/.../
 * data/zcode-wallpaper/) is stable across plugin reinstalls and never dirties
 * the plugin/repo directory; the cli.js path is discovered by probing upward
 * from this module (tsc layout, bundle layout, cache installs).
 */
function launcherHome(): { dir: string; root: string } {
  let dir = path.dirname(fileURLToPath(import.meta.url));
  for (let i = 0; i < 6; i++) {
    if (fs.existsSync(path.join(dir, "dist", "cli.js"))) break;
    dir = path.dirname(dir);
  }
  const home = dataDir();
  fs.mkdirSync(home, { recursive: true });
  return { dir: home, root: dir };
}

// --- cross-platform launch-script builders (pure, unit-tested) -----------------

/** The wrapper shell script: serve first (if the plugin still exists), then
 *  launch ZCode with the canonical CDP + anti-occlusion flags. */
export function buildEarlyLaunchSh(
  node: string,
  cli: string,
  port: number,
  originalCmd: string,
  logFile: string
): string {
  const parts = originalCmd
    .trim()
    .split(/\s+/)
    .filter((t) => t && !t.startsWith("--remote-debugging-port=") && !ANTI_OCCLUSION_FLAGS.includes(t));
  const launch = [...parts, `--remote-debugging-port=${port}`, ...ANTI_OCCLUSION_FLAGS].join(" ");
  return [
    "#!/bin/sh",
    "# zcode-wallpaper early launch zw-launch-v1 (generated by the plugin)",
    `# original ZCode command: ${originalCmd.trim()}`,
    `if [ -f "${cli}" ]; then`,
    `  "${node}" "${cli}" serve --early --port ${port} --api-port ${port + 1} >> "${logFile}" 2>&1 &`,
    "fi",
    launch,
    "",
  ].join("\n");
}

/** macOS variant: launch ZCode via `open -a` with the flags appended. */
export function buildEarlyLaunchCommand(
  node: string,
  cli: string,
  port: number,
  zcodeApp: string,
  logFile: string
): string {
  const flags = [`--remote-debugging-port=${port}`, ...ANTI_OCCLUSION_FLAGS].join(" ");
  return [
    "#!/bin/sh",
    "# zcode-wallpaper early launch zw-launch-v1 (generated by the plugin)",
    `if [ -f "${cli}" ]; then`,
    `  "${node}" "${cli}" serve --early --port ${port} --api-port ${port + 1} >> "${logFile}" 2>&1 &`,
    "fi",
    `open -a "${zcodeApp}" --args ${flags}`,
    "",
  ].join("\n");
}

/** macOS launcher .app bundle: the minimal Info.plist for the shell wrapper. */
export function buildAppBundlePlist(appName: string, bundleId: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${appName}</string>
  <key>CFBundleDisplayName</key><string>${appName}</string>
  <key>CFBundleIdentifier</key><string>${bundleId}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>zw-launch</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSUIElement</key><true/>
</dict>
</plist>
`;
}

/** True when a .desktop Exec line already points at our wrapper. */
export function desktopEntryIsWrapped(execLine: string, wrapperPath: string): boolean {
  const t = execLine.trim();
  if (!t) return false;
  const first = t.split(/\s+/)[0].replace(/^(["'])(.*)\1$/, "$2");
  return path.resolve(first) === path.resolve(wrapperPath);
}

/** True when a .desktop Exec line launches ZCode (any absolute/relative form). */
export function desktopEntryIsZcode(execLine: string): boolean {
  const t = execLine.trim();
  if (!t) return false;
  const first = t.split(/\s+/)[0].replace(/^(["'])(.*)\1$/, "$2");
  const base = path.basename(first).toLowerCase();
  return base === "zcode" || base === "zcode.exe";
}

/** Marker comment preserving the original Exec across rewrites. */
const DESKTOP_MARKER = "X-zcode-wallpaper-exec";

/**
 * Rewrites a .desktop entry's Exec to the wrapper. Returns the ORIGINAL Exec
 * line (from the marker when already wrapped, else the current line) — null
 * when the content has no Exec to work with.
 */
export function rewriteDesktopEntry(content: string, wrapperPath: string): { next: string; original: string } | null {
  const currentExec = /^Exec=(.*)$/m.exec(content)?.[1] ?? "";
  if (!currentExec.trim()) return null;
  const original = /^#\s*X-zcode-wallpaper-exec=(.*)$/m.exec(content)?.[1]?.trim() || currentExec.trim();
  if (desktopEntryIsWrapped(currentExec, wrapperPath)) return { next: content, original };
  const lines = content.split("\n");
  const markerLine = `# ${DESKTOP_MARKER}=${original}`;
  const out: string[] = [];
  let markerPlaced = false;
  for (const line of lines) {
    if (/^#\s*X-zcode-wallpaper-exec=/.test(line)) continue; // replaced below
    if (/^Exec=/.test(line)) {
      out.push(markerLine);
      markerPlaced = true;
      out.push(`Exec=${wrapperPath}`);
    } else {
      out.push(line);
    }
  }
  if (!markerPlaced) {
    // Exec vanished between read and map (shouldn't happen) — nothing to do
    return null;
  }
  return { next: out.join("\n"), original };
}

// --- platform dispatch --------------------------------------------------------

export async function ensureShortcutsHaveCdpFlag(port: number): Promise<ShortcutSyncResult> {
  if (process.platform === "darwin") return ensureMacLauncher(port);
  if (process.platform !== "win32") return ensureLinuxDesktopEntries(port);
  return ensureWindowsShortcuts(port);
}

// --- windows -------------------------------------------------------------------

/** Directories that hold ZCode launch shortcuts, in priority order. */
function shortcutDirs(): string[] {
  const home = process.env.USERPROFILE ?? "";
  const appData = process.env.APPDATA ?? "";
  return [
    // Desktop may be OneDrive-redirected; cover both physical locations.
    path.join(home, "Desktop"),
    ...(process.env.OneDrive ? [path.join(process.env.OneDrive, "Desktop")] : []),
    path.join(appData, "Microsoft", "Windows", "Start Menu", "Programs"),
    path.join("C:", "ProgramData", "Microsoft", "Windows", "Start Menu", "Programs"),
    path.join(appData, "Microsoft", "Internet Explorer", "Quick Launch", "User Pinned", "TaskBar"),
  ];
}

async function ensureWindowsShortcuts(port: number): Promise<ShortcutSyncResult> {
  const result: ShortcutSyncResult = { updated: [], skipped: [], failed: [] };

  const links: string[] = [];
  const collect = (dir: string) => {
    links.push(...fs.readdirSync(dir).filter((f) => /^zcode/i.test(f) && f.endsWith(".lnk")).map((f) => path.join(dir, f)));
  };
  for (const dir of shortcutDirs()) {
    try {
      collect(dir);
      // One subdirectory level (desktop folders like "agent", start-menu groups).
      for (const sub of fs.readdirSync(dir, { withFileTypes: true })) {
        if (!sub.isDirectory()) continue;
        try {
          collect(path.join(dir, sub.name));
        } catch {
          /* unreadable subdir */
        }
      }
    } catch {
      /* dir absent */
    }
  }
  if (links.length === 0) return result;

  // Early-launch wrapper: ZCode spawns plugin hosts ~10s after boot while the
  // renderer page exists at ~1s. Shortcuts get repointed at a generated .vbs
  // that starts the wallpaper serve hidden FIRST, then launches ZCode with
  // the same flags — everything discovered at runtime (ZCode exe from the
  // shortcut's own original target, node from the very process running this
  // plugin, plugin root by probing), so the plugin stays portable.
  const launcher = launcherHome();

  const antiOcclusion = ANTI_OCCLUSION_FLAGS;
  for (const lnk of links) {
    const script = `
$ErrorActionPreference = 'Stop'
try {
  $ws = New-Object -ComObject WScript.Shell
  $s = $ws.CreateShortcut('${lnk.replace(/'/g, "''")}')
  $vbs = '${path.join(launcher.dir, "zw-launch.vbs").replace(/'/g, "''")}'
  $meta = Get-Content -Raw '${path.join(launcher.dir, "zw-launch.json").replace(/'/g, "''")}' -ErrorAction SilentlyContinue | ConvertFrom-Json
  $zcode = $null
  if ($s.TargetPath -match 'ZCode\\.exe$') { $zcode = $s.TargetPath }
  elseif ($s.TargetPath -match 'wscript\\.exe$' -and ([string]$s.Arguments) -match 'zw-launch\\.vbs') {
    # A wrapper from ANY install generation (the shortcut can be pinned to a
    # plugin-cache path that a later update prunes). Its sibling meta json
    # names the ZCode exe; ours is the fallback.
    $vbsArg = ([regex]::Match([string]$s.Arguments, '"([^"]+zw-launch\\.vbs)"')).Groups[1].Value
    if (-not $vbsArg) { $vbsArg = (([string]$s.Arguments -split ' ')[0] -replace '^"|"$','') }
    if ($vbsArg -and (Test-Path $vbsArg)) {
      $metaPath = Join-Path (Split-Path $vbsArg -Parent) 'zw-launch.json'
      if (Test-Path $metaPath) { try { $zcode = (Get-Content -Raw $metaPath | ConvertFrom-Json).zcode } catch {} }
    }
    if (-not $zcode -and $meta) { $zcode = $meta.zcode }
  }
  # Last resort: a shortcut copied from ANOTHER machine (synced Desktop,
  # copied .zcode dir) points at a wrapper path that does not exist here and
  # its meta names a foreign ZCode.exe — the original target is unrecoverable
  # from the .lnk. Probe this machine's install locations instead so the sync
  # can rewrite the entry into a locally valid one instead of skipping forever.
  if (-not $zcode -or -not (Test-Path $zcode)) {
    $cands = @()
    if ($env:ZCODE_WINDOWS_APP_INSTALL_DIR) { $cands += (Join-Path $env:ZCODE_WINDOWS_APP_INSTALL_DIR 'ZCode.exe') }
    $cands += 'C:\\Program Files\\ZCode\\ZCode.exe'
    $cands += (Join-Path $env:LOCALAPPDATA 'Programs\\ZCode\\ZCode.exe')
    foreach ($c in $cands) { if (Test-Path $c) { $zcode = $c; break } }
  }
  if (-not $zcode) { Write-Output 'ok|not-zcode'; exit }
  if (-not (Test-Path $zcode)) { Write-Output 'ok|zcode-missing'; exit }
  $anti = @('${antiOcclusion.join("', '")}')
  # rebuild zcode args: strip wrapper reference + managed flags, append canonical
  $argStr = ([string]$s.Arguments) -replace '^"[^"]*zw-launch\.vbs"\s*','' -replace '^\S*zw-launch\.vbs\s*',''
  $parts = @($argStr -split ' ' | Where-Object { $_ -ne '' -and $_ -notlike '--remote-debugging-port=*' -and $anti -notcontains $_ })
  $canonical = @('--remote-debugging-port=${port}') + $anti
  $zargs = ($parts + $canonical) -join ' '
  $newArgs = '"' + $vbs + '" ' + $zargs
  # Wrapper staleness: an .lnk can already be perfectly pointed at a wrapper
  # whose CONTENT is broken or outdated (0.3.0 shipped one without the
  # sh.Run prefix; pre-0.4.1 ones broke launches after uninstall). The
  # zw-wrapper-vN marker detects that — bump N with every wrapper change and
  # a stale wrapper is regenerated without touching the shortcut.
  $stale = -not (Test-Path $vbs) -or -not ((Get-Content -Raw $vbs -ErrorAction SilentlyContinue) -match 'zw-wrapper-v3')
  if (-not $stale -and $s.TargetPath -eq 'wscript.exe' -and ([string]$s.Arguments) -eq $newArgs) { Write-Output 'ok|has-flag'; exit }
  if ($s.TargetPath -ne 'wscript.exe' -or ([string]$s.Arguments) -ne $newArgs) {
    $icon = $zcode + ',0'
    if (-not $s.IconLocation -or $s.IconLocation -eq ',0' -or $s.IconLocation -like '*zw-launch*') { $s.IconLocation = $icon }
    $s.WorkingDirectory = Split-Path $zcode -Parent
    $s.TargetPath = 'wscript.exe'
    $s.Arguments = $newArgs
    $s.Save()
  }
  Write-Output ('updated|' + $zcode)
} catch { Write-Output ('err|' + $_.Exception.Message) }`;
    try {
      const { stdout } = await exec("powershell", ["-NoProfile", "-Command", script], { timeout: 15_000, windowsHide: true });
      const out = stdout.trim();
      if (out.startsWith("updated")) {
        result.updated.push(lnk);
        const zcode = out.slice(out.indexOf("|") + 1);
        if (zcode) writeEarlyLaunchVbs(port, zcode, launcher);
      } else if (out.startsWith("err")) result.failed.push({ path: lnk, reason: out.slice(4) });
      else result.skipped.push(lnk);
    } catch (err) {
      result.failed.push({ path: lnk, reason: (err as Error).message });
    }
  }
  return result;
}

/** Writes zw-launch.vbs (+ meta json). The ZCode path comes from the user's
 *  own shortcut (discovered per machine — nothing hardcoded); node is the
 *  process running the plugin right now. Idempotent. */
function writeEarlyLaunchVbs(port: number, zcode: string, launcher: { dir: string; root: string }): void {
  const anti = ANTI_OCCLUSION_FLAGS;
  const cli = path.join(launcher.root, "dist", "cli.js");
  const node = process.execPath;
  if (!fs.existsSync(cli) || !fs.existsSync(node)) return;
  // VBS string literals double every embedded quote; sh.Run takes a full
  // command line, so each token is quoted and every quote doubled.
  const DQ = String.fromCharCode(34);
  const vbq = (v: string) => DQ + DQ + v + DQ + DQ;
  const serveCmd = [vbq(node), vbq(cli), "serve", "--early", "--port", String(port), "--api-port", String(port + 1)].join(" ");
  const zcodeCmd = [vbq(zcode), "--remote-debugging-port=" + port].concat(anti).join(" ");
  // Self-healing against uninstall: shortcuts point HERE, and ZCode's plugin
  // system has no uninstall hook to restore them — if the plugin (this cli.js)
  // is gone, a wrapper that blindly runs node would error on every launch
  // ("deleted the plugin, ZCode won't start"). Skip the serve, still launch
  // ZCode. The shortcut stays until the next install rewrites the wrapper.
  const lines = [
    String.fromCharCode(39) + " zcode-wallpaper early launch zw-wrapper-v3 (generated by the plugin)",
    String.fromCharCode(39) + " Starts the wallpaper serve hidden BEFORE ZCode so the renderer page",
    String.fromCharCode(39) + " is injected the moment it exists (plugin hosts spawn ~10s later).",
    String.fromCharCode(39) + " If the plugin was uninstalled, the serve step is skipped and ZCode",
    String.fromCharCode(39) + " still launches normally.",
    "Set sh = CreateObject(\"WScript.Shell\")",
    "Set fso = CreateObject(\"Scripting.FileSystemObject\")",
    // FileExists takes a plain string literal (single quotes) — NOT the
    // doubled sh.Run command-line escaping (cscript compile-checks this).
    "If fso.FileExists(" + DQ + cli + DQ + ") Then",
    "  sh.Run " + DQ + serveCmd + DQ + ", 0, False",
    "End If",
    "sh.Run " + DQ + zcodeCmd + DQ + ", 1, False",
  ];
  try {
    const metaPath = path.join(launcher.dir, "zw-launch.json");
    const prev = fs.existsSync(metaPath) ? (JSON.parse(fs.readFileSync(metaPath, "utf8")) as Record<string, unknown>) : {};
    fs.writeFileSync(metaPath, JSON.stringify({ ...prev, zcode, port }, null, 1));
    const crlf = String.fromCharCode(13, 10);
    fs.writeFileSync(path.join(launcher.dir, "zw-launch.vbs"), lines.join(crlf) + crlf, { encoding: "utf-8" });
  } catch {
    /* unwritable location - shortcuts fall back to plain flag mode */
  }
}

// --- macOS -----------------------------------------------------------------------

const MAC_ZCODE_CANDIDATES = ["/Applications/ZCode.app", path.join(os.homedir(), "Applications", "ZCode.app")];

/**
 * Generates "ZCode Wallpaper.app" in ~/Applications — the macOS equivalent of
 * the Windows shortcut wrapper. macOS has no supported way to inject launch
 * args into Dock/Spotlight launches, so while the wallpaper plugin is enabled
 * the user launches ZCode through this app. Idempotent; rewritten whenever
 * the node/cli paths change.
 */
async function ensureMacLauncher(port: number): Promise<ShortcutSyncResult> {
  const result: ShortcutSyncResult = { updated: [], skipped: [], failed: [] };
  const zcodeApp = MAC_ZCODE_CANDIDATES.find((p) => fs.existsSync(p));
  if (!zcodeApp) {
    result.skipped.push("ZCode.app not found");
    return result;
  }
  const { dir, root } = launcherHome();
  const cli = path.join(root, "dist", "cli.js");
  if (!fs.existsSync(cli)) {
    result.skipped.push("plugin install not found");
    return result;
  }
  const appName = "ZCode Wallpaper.app";
  const appDir = path.join(os.homedir(), "Applications", appName);
  const scriptPath = path.join(appDir, "Contents", "MacOS", "zw-launch");
  const plistPath = path.join(appDir, "Contents", "Info.plist");
  const want = buildEarlyLaunchCommand(process.execPath, cli, port, zcodeApp, path.join(dir, "early.log"));
  try {
    const same =
      fs.existsSync(scriptPath) && fs.existsSync(plistPath) && fs.readFileSync(scriptPath, "utf8") === want;
    if (same) {
      result.skipped.push(appDir);
    } else {
      fs.mkdirSync(path.dirname(scriptPath), { recursive: true });
      fs.writeFileSync(scriptPath, want);
      fs.chmodSync(scriptPath, 0o755);
      fs.writeFileSync(plistPath, buildAppBundlePlist("ZCode Wallpaper", "com.zcode-wallpaper.early"));
      result.updated.push(appDir);
    }
  } catch (err) {
    result.failed.push({ path: appDir, reason: (err as Error).message });
  }
  return result;
}

// --- linux -----------------------------------------------------------------------

/**
 * Rewrites user-scope .desktop entries that launch ZCode to a wrapper script
 * that starts the serve first. System entries under /usr/share need root and
 * are left alone; a user who installed system-wide can copy one into
 * ~/.local/share/applications to opt in. Idempotent via the marker comment.
 */
async function ensureLinuxDesktopEntries(port: number): Promise<ShortcutSyncResult> {
  const result: ShortcutSyncResult = { updated: [], skipped: [], failed: [] };
  const base = path.join(os.homedir(), ".local", "share", "applications");
  const dirs = [base, path.join(base, "ZCode")];
  const entries: string[] = [];
  for (const d of dirs) {
    try {
      entries.push(...fs.readdirSync(d).filter((f) => f.endsWith(".desktop")).map((f) => path.join(d, f)));
    } catch {
      /* dir absent */
    }
  }
  if (entries.length === 0) return result;

  const { dir, root } = launcherHome();
  const cli = path.join(root, "dist", "cli.js");
  if (!fs.existsSync(cli)) {
    result.skipped.push("plugin install not found");
    return result;
  }
  const wrapper = path.join(dir, "zw-launch.sh");
  const logFile = path.join(dir, "early.log");
  let wrapperWritten = false;

  for (const entry of entries) {
    try {
      const content = fs.readFileSync(entry, "utf8");
      const currentExec = /^Exec=(.*)$/m.exec(content)?.[1] ?? "";
      if (!desktopEntryIsZcode(currentExec) && !desktopEntryIsWrapped(currentExec, wrapper)) {
        result.skipped.push(entry);
        continue;
      }
      const r = rewriteDesktopEntry(content, wrapper);
      if (!r) {
        result.skipped.push(entry);
        continue;
      }
      // refresh the wrapper every pass — paths may have changed across
      // reinstalls, and it is cheap to rewrite one small script
      fs.writeFileSync(wrapper, buildEarlyLaunchSh(process.execPath, cli, port, r.original, logFile));
      fs.chmodSync(wrapper, 0o755);
      wrapperWritten = true;
      if (r.next !== content) {
        fs.writeFileSync(entry, r.next);
        result.updated.push(entry);
      } else {
        result.skipped.push(entry);
      }
    } catch (err) {
      result.failed.push({ path: entry, reason: (err as Error).message });
    }
  }
  void wrapperWritten;
  return result;
}
