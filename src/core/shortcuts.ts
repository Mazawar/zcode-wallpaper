/**
 * Rewrites user-scope .desktop entries that launch ZCode to a wrapper script
 * that starts the serve first. System entries under /usr/share need root and
 * are left alone; a user who installed system-wide can copy one into
 * ~/.local/share/applications to opt in. Idempotent via the marker comment.
 */
async function ensureLinuxDesktopEntries(port: number): Promise<ShortcutSyncResult> {
  const result: ShortcutSyncResult = { updated: [], skipped: [], failed: [] };
  const base = path.join(os.homedir(), ".local", "share", "applications");
  const dirs = [base, path.join(base, "ZCode")];
  const entries: string[] = [];
  for (const d of dirs) {
    try {
      entries.push(...fs.readdirSync(d).filter((f) => f.endsWith(".desktop")).map((f) => path.join(d, f)));
    } catch {
      /* dir absent */
    }
  }
  if (entries.length === 0) return result;

  const { dir, root } = launcherHome();
  const cli = path.join(root, "dist", "cli.js");
  if (!fs.existsSync(cli)) {
    result.skipped.push("plugin install not found");
    return result;
  }
  const wrapper = path.join(dir, "zw-launch.sh");
  const logFile = path.join(dir, "early.log");
  let wrapperWritten = false;

  for (const entry of entries) {
    try {
      const content = fs.readFileSync(entry, "utf8");
      const currentExec = /^Exec=(.*)$/m.exec(content)?.[1] ?? "";
      if (!desktopEntryIsZcode(currentExec) && !desktopEntryIsWrapped(currentExec, wrapper)) {
        result.skipped.push(entry);
        continue;
      }
      const r = rewriteDesktopEntry(content, wrapper);
      if (!r) {
        result.skipped.push(entry);
        continue;
      }
      // refresh the wrapper every pass — paths may have changed across
      // reinstalls, and it is cheap to rewrite one small script
      fs.writeFileSync(wrapper, buildEarlyLaunchSh(process.execPath, cli, port, r.original, logFile));
      fs.chmodSync(wrapper, 0o755);
      wrapperWritten = true;
      if (r.next !== content) {
        fs.writeFileSync(entry, r.next);
        result.updated.push(entry);
      } else {
        result.skipped.push(entry);
      }
    } catch (err) {
      result.failed.push({ path: entry, reason: (err as Error).message });
    }
  }
  void wrapperWritten;
  return result;
}
