/**
 * Early-launch support, per platform — starts the wallpaper serve BEFORE
 * ZCode so the renderer is injected the moment it exists (plugin hosts spawn
 * ~10s later), and puts the CDP flag on the launch (ZCode only accepts
 * --remote-debugging-port at process start; a launch without it means no
 * injection for that whole session):
 *   win32   rewrite ZCode .lnk shortcuts to a generated wscript wrapper
 *   darwin  generate a launcher .app bundle in ~/Applications the user
 *           launches instead of ZCode (serve first, then
 *           `open -a ZCode --args --remote-debugging-port=…`)
 *   linux   rewrite user-scope .desktop entries to a wrapper script
 *
 * Two hard rules (D18): the plugin never touches machine configuration
 * (registry Run keys / autostart / LaunchAgents are off-limits — only the
 * user's own launch shortcuts and this plugin's data dir), and a wrapper
 * must never be able to BLOCK ZCode from starting: the serve step only runs
 * when BOTH the node executable and the plugin install exist, and the ZCode
 * launch runs unconditionally. Node/cli paths are baked per machine and
 * self-heal on every plugin session (an nvm move degrades to "no early
 * serve" until then, never to "ZCode won't start" — the 1.0.2 incident).
 * Content builders are pure and unit-tested; only the scanning parts touch
 * the OS.
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileP as exec } from "./exec.js";
import { dataDir } from "./launch.js";

export interface ShortcutSyncResult {
  /** Shortcuts that gained the flag this run. */
  updated: string[];
  /** Shortcuts already carrying the flag (or not pointing at ZCode.exe). */
  skipped: string[];
  /** Shortcuts that could not be saved (typically ProgramData without elevation). */
  failed: Array<{ path: string; reason: string }>;
}

/** Chromium flags that stop occlusion misdetection from freezing media/rAF. */
export const ANTI_OCCLUSION_FLAGS = [
  "--disable-backgrounding-occluded-windows",
  "--disable-renderer-backgrounding",
];

/**
 * Where the generated launcher artifacts live. The data dir (~/.zcode/.../
 * data/zcode-wallpaper/) is stable across plugin reinstalls and never dirties
 * the plugin/repo directory; the cli.js path is discovered by probing upward
 * from this module (tsc layout, bundle layout, cache installs).
 */
function launcherHome(): { dir: string; root: string } {
  let dir = path.dirname(fileURLToPath(import.meta.url));
  for (let i = 0; i < 6; i++) {
    if (fs.existsSync(path.join(dir, "dist", "cli.js"))) break;
    dir = path.dirname(dir);
  }
  const home = dataDir();
  fs.mkdirSync(home, { recursive: true });
  return { dir: home, root: dir };
}

// --- cross-platform launch-script builders (pure, unit-tested) -----------------

/** The wrapper shell script: serve first (only if node AND the plugin both
 *  exist — a wrapper must never block the launch), then launch ZCode with
 *  the canonical CDP + anti-occlusion flags. */
export function buildEarlyLaunchSh(
  node: string,
  cli: string,
  port: number,
  originalCmd: string,
  logFile: string
): string {
  const parts = originalCmd
    .trim()
    .split(/\s+/)
    .filter((t) => t && !t.startsWith("--remote-debugging-port=") && !ANTI_OCCLUSION_FLAGS.includes(t));
  const launch = [...parts, `--remote-debugging-port=${port}`, ...ANTI_OCCLUSION_FLAGS].join(" ");
  return [
    "#!/bin/sh",
    "# zcode-wallpaper early launch zw-launch-v1 (generated by the plugin)",
    `# original ZCode command: ${originalCmd.trim()}`,
    `if [ -f "${cli}" ] && [ -x "${node}" ]; then`,
    `  "${node}" "${cli}" serve --early --port ${port} --api-port ${port + 1} >> "${logFile}" 2>&1 &`,
    "fi",
    launch,
    "",
  ].join("\n");
}

/** macOS variant: launch ZCode via `open -a` with the flags appended. The
 *  app is addressed by NAME (open searches /Applications + ~/Applications),
 *  so a moved install keeps launching instead of dying on a stale path. */
export function buildEarlyLaunchCommand(
  node: string,
  cli: string,
  port: number,
  zcodeApp: string,
  logFile: string
): string {
  const appName = path.basename(zcodeApp).replace(/\.app$/, "");
  const flags = [`--remote-debugging-port=${port}`, ...ANTI_OCCLUSION_FLAGS].join(" ");
  return [
    "#!/bin/sh",
    "# zcode-wallpaper early launch zw-launch-v1 (generated by the plugin)",
    `if [ -f "${cli}" ] && [ -x "${node}" ]; then`,
    `  "${node}" "${cli}" serve --early --port ${port} --api-port ${port + 1} >> "${logFile}" 2>&1 &`,
    "fi",
    `open -a "${appName}" --args ${flags}`,
    "",
  ].join("\n");
}

/** macOS launcher .app bundle: the minimal Info.plist for the shell wrapper. */
export function buildAppBundlePlist(appName: string, bundleId: string): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${appName}</string>
  <key>CFBundleDisplayName</key><string>${appName}</string>
  <key>CFBundleIdentifier</key><string>${bundleId}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>zw-launch</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSUIElement</key><true/>
</dict>
</plist>
`;
}

/** True when a .desktop Exec line already points at our wrapper. */
export function desktopEntryIsWrapped(execLine: string, wrapperPath: string): boolean {
  const t = execLine.trim();
  if (!t) return false;
  const first = t.split(/\s+/)[0].replace(/^(["'])(.*)\1$/, "$2");
  return path.resolve(first) === path.resolve(wrapperPath);
}

/** True when a .desktop Exec line launches ZCode (any absolute/relative form). */
export function desktopEntryIsZcode(execLine: string): boolean {
  const t = execLine.trim();
  if (!t) return false;
  const first = t.split(/\s+/)[0].replace(/^(["'])(.*)\1$/, "$2");
  const base = path.basename(first).toLowerCase();
  return base === "zcode" || base === "zcode.exe";
}

/** Marker comment preserving the original Exec across rewrites. */
const DESKTOP_MARKER = "X-zcode-wallpaper-exec";

/**
 * Rewrites a .desktop entry's Exec to the wrapper. Returns the ORIGINAL Exec
 * line (from the marker when already wrapped, else the current line) — null
 * when the content has no Exec to work with.
 */
export function rewriteDesktopEntry(content: string, wrapperPath: string): { next: string; original: string } | null {
  const currentExec = /^Exec=(.*)$/m.exec(content)?.[1] ?? "";
  if (!currentExec.trim()) return null;
  const original = /^#\s*X-zcode-wallpaper-exec=(.*)$/m.exec(content)?.[1]?.trim() || currentExec.trim();
  if (desktopEntryIsWrapped(currentExec, wrapperPath)) return { next: content, original };
  const lines = content.split("\n");
  const markerLine = `# ${DESKTOP_MARKER}=${original}`;
  const out: string[] = [];
  let markerPlaced = false;
  for (const line of lines) {
    if (/^#\s*X-zcode-wallpaper-exec=/.test(line)) continue; // replaced below
    if (/^Exec=/.test(line)) {
      out.push(markerLine);
      markerPlaced = true;
      out.push(`Exec=${wrapperPath}`);
    } else {
      out.push(line);
    }
  }
  if (!markerPlaced) {
    // Exec vanished between read and map (shouldn't happen) — nothing to do
    return null;
  }
  return { next: out.join("\n"), original };
}

